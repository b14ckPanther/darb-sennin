// Builds src/design/icons/solar.generated.json from manifest.json and @iconify-json/solar.
// Only the glyphs the app names are bundled; nothing is fetched at runtime.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const dir = resolve(here, '../src/design/icons')
const manifest = JSON.parse(readFileSync(resolve(dir, 'manifest.json'), 'utf8'))
const require = createRequire(import.meta.url)
const set = require(`@iconify-json/${manifest.set}/icons.json`)

const icons = {}
for (const [name, base] of Object.entries(manifest.icons)) {
    icons[name] = {}
    for (const variant of manifest.variants) {
        const key = `${base}-${variant}`
        const alias = set.aliases?.[key]
        if (alias && Object.keys(alias).some((k) => k !== 'parent')) {
            throw new Error(`Alias "${key}" carries transforms; pick another glyph`)
        }
        const glyph = set.icons[alias ? alias.parent : key]
        if (!glyph) {
            throw new Error(`Missing ${manifest.set} icon "${key}" for "${name}"`)
        }
        icons[name][variant] = glyph.body
    }
}

const out = {
    $comment: `Generated by scripts/build-icons.mjs from @iconify-json/${manifest.set} (${set.info?.license?.title ?? 'see ASSETS.md'}). Do not edit.`,
    width: set.width ?? 24,
    height: set.height ?? 24,
    icons,
}
writeFileSync(resolve(dir, 'solar.generated.json'), `${JSON.stringify(out, null, 2)}\n`)
console.log(
    `icons: wrote ${String(Object.keys(icons).length)} glyphs x ${String(manifest.variants.length)} variants`,
)
